end

"""
    rotation_zz([eltype::Type{<:Complex}], [symmetry::Type{<:Sector}]; theta)
    Rzz([eltype::Type{<:Complex}], [symmetry::Type{<:Sector}]; theta)

The ZZ-rotation gate ``e^{-iθ\\, Z ⊗ Z / 2} = \\cos\\tfrac{θ}{2}\\,I ⊗ I - i\\sin\\tfrac{θ}{2}\\,Z ⊗ Z``,
